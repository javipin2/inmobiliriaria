// Language switcher functionality
class LanguageSwitcher {
    constructor() {
        this.currentLang = localStorage.getItem('language') || 'es';
        this.init();
    }

    init() {
        // Set initial language
        this.setLanguage(this.currentLang);
        
        // Language dropdown functionality
        const languageBtn = document.getElementById('languageBtn');
        const languageMenu = document.getElementById('languageMenu');
        
        if (languageBtn && languageMenu) {
            // Toggle menu on button click
            languageBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                const isActive = languageMenu.classList.contains('active');
                languageMenu.classList.toggle('active');
                languageBtn.setAttribute('aria-expanded', !isActive);
            });
            
            // Close menu when clicking outside
            document.addEventListener('click', (e) => {
                if (!languageBtn.contains(e.target) && !languageMenu.contains(e.target)) {
                    languageMenu.classList.remove('active');
                    languageBtn.setAttribute('aria-expanded', 'false');
                }
            });
            
            // Add event listeners to language options
            document.querySelectorAll('.language-option').forEach(option => {
                option.addEventListener('click', (e) => {
                    e.stopPropagation();
                    const lang = option.getAttribute('data-lang');
                    this.setLanguage(lang);
                    languageMenu.classList.remove('active');
                    languageBtn.setAttribute('aria-expanded', 'false');
                });
            });
        }
    }

    setLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('language', lang);
        
        // Update active language option
        document.querySelectorAll('.language-option').forEach(option => {
            option.classList.remove('active');
            if (option.getAttribute('data-lang') === lang) {
                option.classList.add('active');
            }
        });
        
        
        // Update document title and meta description if needed
        if (lang === 'es') {
            document.title = 'AG Servivicios inmobiliarios';
            document.querySelector('meta[name="description"]').content = 'En AG Servivicios inmobiliarios te ayudamos a comprar, vender o alquilar tu piso en Barcelona. Personal shopper inmobiliario y gestión de fincas.';
        } else if (lang === 'en') {
            document.title = 'AG Servivicios inmobiliarios';
            document.querySelector('meta[name="description"]').content = 'At AG Servivicios inmobiliarios we help you buy, sell or rent your apartment in Barcelona. Real estate personal shopper and property management.';
        } else if (lang === 'ca') {
            document.title = 'AG Servivicios inmobiliarios';
            document.querySelector('meta[name="description"]').content = 'A AG Servivicios inmobiliarios t\'ajudem a comprar, vendre o llogar el teu pis a Barcelona. Personal shopper immobiliari i gestió de finques.';
        }

        // Update document language
        document.documentElement.lang = lang;

        // Translate all elements
        this.translatePage(translations[lang]);

        // Update WhatsApp button URL
        this.updateWhatsAppUrl(translations[lang].whatsapp.message);

        // Re-render properties if they exist
        if (typeof renderProperties === 'function') {
            renderProperties();
        }
    }

    translatePage(trans) {
        // Translate elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const keys = key.split('.');
            let value = trans;
            
            for (const k of keys) {
                value = value[k];
            }
            
            if (value !== undefined) {
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    // For inputs, update placeholder if it has data-i18n-placeholder
                    const placeholderKey = element.getAttribute('data-i18n-placeholder');
                    if (placeholderKey) {
                        const placeholderKeys = placeholderKey.split('.');
                        let placeholderValue = trans;
                        for (const k of placeholderKeys) {
                            placeholderValue = placeholderValue[k];
                        }
                        if (placeholderValue !== undefined) {
                            element.placeholder = placeholderValue;
                        }
                    }
                } else if (element.tagName === 'OPTION') {
                    element.textContent = value;
                } else {
                    element.textContent = value;
                }
            }
        });
    }

    updateWhatsAppUrl(message) {
        const whatsappBtn = document.getElementById('whatsappBtn');
        if (whatsappBtn) {
            const encodedMessage = encodeURIComponent(message);
            whatsappBtn.href = `https://wa.me/34651640323?text=${encodedMessage}`;
        }

        // Update all WhatsApp links
        document.querySelectorAll('.whatsapp-btn').forEach(btn => {
            if (btn.id !== 'whatsappBtn') {
                const encodedMessage = encodeURIComponent(message);
                btn.href = `https://wa.me/34651640323?text=${encodedMessage}`;
            }
        });
    }
}

// Initialize language switcher when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        new LanguageSwitcher();
    });
} else {
    new LanguageSwitcher();
}

